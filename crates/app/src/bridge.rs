//! The generated glue: `index.html` and `tv-bridge.js`.
//!
//! A payload is a web app that knows nothing about televisions — that is the point of
//! the handoff. Something has to sit between it and the remote control, and this
//! module writes that something:
//!
//! - `tv-bridge.js` listens for DOM key events, maps them through
//!   [`crate::keys`]'s vocabulary, and calls the payload's `key_event(name, value)`.
//!   It also drives `boot()` and a `requestAnimationFrame` loop calling `tick(now)`,
//!   and exposes `window.tvBridge.send(json)` / `.snapshot()` over the payload's
//!   `dispatch` and `snapshot`.
//! - `index.html` is a black, full-bleed document that loads the bridge — used only
//!   when the payload does not bring its own entry document.
//!
//! The payload interface is the one the handoff's wrapper already spoke
//! (`boot`/`tick`/`snapshot`/`dispatch`/`key_event`), so an existing payload moves
//! over without being rewritten. Every call is optional: a payload that implements
//! only `key_event` is a valid payload.

use crate::descriptor::AppDescriptor;
use crate::keys::Key;

/// The global the bridge looks for by default.
pub const DEFAULT_PAYLOAD_GLOBAL: &str = "tvPayload";

/// How the bridge should reach its payload.
#[derive(Debug, Clone)]
pub struct BridgeOptions {
    /// The global the payload attaches itself to, e.g. `tvPayload`.
    pub payload_global: String,
    /// Vendor key numbers, as `(keyCode, key)`.
    ///
    /// Tizen and webOS use different numbers for back and exit, and those numbers
    /// have moved between model years. They are a deployment fact, so the bridge
    /// takes them here instead of shipping a guess — a wrong guess is an app whose
    /// back button silently does nothing on half the walls.
    pub extra_key_codes: Vec<(u32, Key)>,
}

impl Default for BridgeOptions {
    fn default() -> Self {
        Self {
            payload_global: DEFAULT_PAYLOAD_GLOBAL.to_string(),
            extra_key_codes: Vec::new(),
        }
    }
}

impl BridgeOptions {
    /// Options for a payload under a given global, with no vendor codes.
    #[must_use]
    pub fn for_payload(payload_global: impl Into<String>) -> Self {
        Self {
            payload_global: payload_global.into(),
            extra_key_codes: Vec::new(),
        }
    }

    /// Adds a vendor key number.
    #[must_use]
    pub fn with_key_code(mut self, key_code: u32, key: Key) -> Self {
        self.extra_key_codes.push((key_code, key));
        self
    }
}

/// The bridge script, generated for a descriptor.
///
/// # Errors
///
/// Returns [`crate::AppError::InvalidDescriptor`] when the descriptor does not
/// validate: the script embeds the app id and name, and a broken id in a generated
/// file is a broken id in the app.
pub fn bridge_js(descriptor: &AppDescriptor) -> Result<String, crate::AppError> {
    bridge_js_with(descriptor, &BridgeOptions::default())
}

/// The bridge script, with explicit options.
///
/// # Errors
///
/// Returns [`crate::AppError::InvalidDescriptor`] when the descriptor does not
/// validate.
pub fn bridge_js_with(
    descriptor: &AppDescriptor,
    options: &BridgeOptions,
) -> Result<String, crate::AppError> {
    descriptor.validate()?;

    let event_names: Vec<String> = Key::ALL
        .iter()
        .flat_map(|key| event_names_for(*key).into_iter().map(|name| (name, *key)))
        .map(|(name, key)| format!("    {name}: '{}',", key.as_str()))
        .collect();
    let key_codes: Vec<String> = Key::ALL
        .iter()
        .flat_map(|key| key_codes_for(*key).into_iter().map(|code| (code, *key)))
        .map(|(code, key)| format!("    {code}: '{}',", key.as_str()))
        .collect();
    let extra: Vec<String> = options
        .extra_key_codes
        .iter()
        .map(|(code, key)| format!("    {code}: '{}',", key.as_str()))
        .collect();

    let mut js = String::with_capacity(2048);
    js.push_str(&format!(
        "/* tv-bridge.js — generated by tv-rs-app for {} ({}) {}.\n",
        js_comment_safe(&descriptor.id),
        js_comment_safe(&descriptor.name),
        js_comment_safe(&descriptor.version)
    ));
    js.push_str(
        " * Do not edit by hand: regenerate it, or edit the descriptor and package again.\n",
    );
    js.push_str(" */\n");
    js.push_str("(function () {\n  'use strict';\n\n");
    js.push_str(&format!(
        "  var PAYLOAD_GLOBAL = '{}';\n\n",
        js_string_safe(&options.payload_global)
    ));

    js.push_str("  // Standard DOM event names, as both Tizen and webOS deliver them.\n");
    js.push_str("  var EVENT_NAMES = {\n");
    js.push_str(&event_names.join("\n"));
    js.push_str("\n  };\n\n");

    js.push_str("  // The legacy numbers that are the same on every platform.\n");
    js.push_str("  var KEY_CODES = {\n");
    js.push_str(&key_codes.join("\n"));
    js.push_str("\n  };\n\n");

    js.push_str(
        "  // Vendor numbers for back and exit: they differ by platform and by model\n\
         \x20 // year, so a deployment supplies them rather than inheriting a guess.\n",
    );
    js.push_str("  var EXTRA_KEY_CODES = {\n");
    if !extra.is_empty() {
        js.push_str(&extra.join("\n"));
        js.push('\n');
    }
    js.push_str("  };\n\n");

    js.push_str(BRIDGE_BODY);
    Ok(js)
}

/// A minimal entry document that loads the bridge, for payloads without their own.
///
/// # Errors
///
/// Returns [`crate::AppError::InvalidDescriptor`] when the descriptor does not
/// validate.
pub fn index_html(descriptor: &AppDescriptor) -> Result<String, crate::AppError> {
    descriptor.validate()?;
    let title = html_escape(&descriptor.name);
    Ok(format!(
        "<!DOCTYPE html>\n\
<html lang=\"en\">\n\
  <head>\n\
    <meta charset=\"utf-8\">\n\
    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
    <title>{title}</title>\n\
    <style>\n\
      html, body {{ margin: 0; padding: 0; height: 100%; overflow: hidden;\n\
                    background: #000; color: #fff; }}\n\
      #tv-root {{ position: absolute; inset: 0; }}\n\
    </style>\n\
  </head>\n\
  <body>\n\
    <div id=\"tv-root\"></div>\n\
    <!-- The payload's own script tag goes here; it is expected to attach itself to\n\
         window.{} so the bridge can find it. -->\n\
    <script src=\"tv-bridge.js\"></script>\n\
  </body>\n\
</html>\n",
        DEFAULT_PAYLOAD_GLOBAL
    ))
}

/// The bridge's runtime, kept as a constant so the generated file has exactly one
/// source of truth.
const BRIDGE_BODY: &str = r"  function payload() {
    return window[PAYLOAD_GLOBAL] || null;
  }

  function call(name, first, second) {
    var target = payload();
    if (target && typeof target[name] === 'function') {
      return target[name](first, second);
    }
    return undefined;
  }

  function keyFor(event) {
    var byName = EVENT_NAMES[event.code] || EVENT_NAMES[event.key];
    if (byName) {
      return byName;
    }
    var byCode = KEY_CODES[event.keyCode] || EXTRA_KEY_CODES[event.keyCode];
    return byCode || null;
  }

  // value is 1 while the key is held and 0 when it is released, which is the shape
  // the payload's key_event already expects.
  function forward(event, value) {
    var key = keyFor(event);
    if (!key) {
      return;
    }
    event.preventDefault();
    call('key_event', key, value);
  }

  function frame(now) {
    call('tick', now);
    window.requestAnimationFrame(frame);
  }

  function start() {
    call('boot');
    window.requestAnimationFrame(frame);
    window.addEventListener('keydown', function (event) { forward(event, 1); });
    window.addEventListener('keyup', function (event) { forward(event, 0); });
  }

  // The outbound path: the payload decides what to do with the JSON, the bridge only
  // carries it.
  window.tvBridge = {
    send: function (json) { return call('dispatch', json); },
    snapshot: function () { return call('snapshot'); }
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
})();
";

/// The event names that resolve to a key, as `(name, key)` pairs, for the generator.
fn event_names_for(key: Key) -> Vec<&'static str> {
    match key {
        Key::Up => vec!["ArrowUp"],
        Key::Down => vec!["ArrowDown"],
        Key::Left => vec!["ArrowLeft"],
        Key::Right => vec!["ArrowRight"],
        Key::Select => vec!["Enter", "Select"],
        Key::Back => vec!["GoBack", "BrowserBack"],
        Key::Home => vec!["Home"],
        Key::Exit => vec!["Exit", "Escape"],
        Key::Play => vec!["MediaPlay"],
        Key::Pause => vec!["MediaPause"],
        Key::Stop => vec!["MediaStop"],
    }
}

/// The standard numeric codes for a key, as `(code, key)` pairs.
fn key_codes_for(key: Key) -> Vec<u32> {
    match key {
        Key::Up => vec![38],
        Key::Down => vec![40],
        Key::Left => vec![37],
        Key::Right => vec![39],
        Key::Select => vec![13],
        _ => Vec::new(),
    }
}

/// Keeps operator text from breaking out of the generated comment.
fn js_comment_safe(value: &str) -> String {
    value.replace("*/", "*\\/").replace('\n', " ")
}

/// Keeps operator text from breaking out of a generated string literal.
fn js_string_safe(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('\'', "\\'")
        .replace('\n', "\\n")
}

fn html_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn descriptor() -> AppDescriptor {
        AppDescriptor::new("com.example.wall", "Lobby wall", "1.0.0")
    }

    #[test]
    fn the_bridge_maps_the_dpad_and_the_back_key() {
        let js = bridge_js(&descriptor()).unwrap();
        assert!(js.contains("ArrowUp: 'Up'"));
        assert!(js.contains("ArrowDown: 'Down'"));
        assert!(js.contains("ArrowLeft: 'Left'"));
        assert!(js.contains("ArrowRight: 'Right'"));
        assert!(js.contains("Enter: 'Select'"));
        assert!(js.contains("GoBack: 'Back'"));
        assert!(js.contains("BrowserBack: 'Back'"));
        assert!(js.contains("38: 'Up'"));
        assert!(js.contains("13: 'Select'"));
    }

    #[test]
    fn the_bridge_calls_the_payload_interface_the_handoff_already_spoke() {
        let js = bridge_js(&descriptor()).unwrap();
        for call in [
            "'boot'",
            "'tick'",
            "'snapshot'",
            "'dispatch'",
            "'key_event'",
        ] {
            assert!(js.contains(call), "bridge should call {call}");
        }
        assert!(js.contains("window.tvBridge"));
    }

    #[test]
    fn a_payload_global_can_be_chosen() {
        let options = BridgeOptions::for_payload("myPayload");
        let js = bridge_js_with(&descriptor(), &options).unwrap();
        assert!(js.contains("var PAYLOAD_GLOBAL = 'myPayload';"));
        assert!(!js.contains("tvPayload"));
    }

    #[test]
    fn vendor_key_numbers_come_from_the_deployment() {
        let options = BridgeOptions::default().with_key_code(10009, Key::Back);
        let js = bridge_js_with(&descriptor(), &options).unwrap();
        assert!(js.contains("10009: 'Back'"), "{js}");
        // Without them the table is empty rather than carrying a guess.
        let bare = bridge_js(&descriptor()).unwrap();
        assert!(!bare.contains("10009"));
    }

    #[test]
    fn operator_text_cannot_break_out_of_the_generated_file() {
        let descriptor = AppDescriptor::new("com.example.wall", "Wall */ alert(1) /*", "1.0.0");
        let js = bridge_js(&descriptor).unwrap();
        assert!(!js.contains("*/ alert(1)"), "{js}");
        let html = index_html(&descriptor).unwrap();
        assert!(html.contains("Wall */ alert(1) /*"));
    }

    #[test]
    fn the_entry_document_loads_the_bridge_and_is_full_bleed() {
        let html = index_html(&descriptor()).unwrap();
        assert!(html.starts_with("<!DOCTYPE html>"));
        assert!(html.contains("<title>Lobby wall</title>"));
        assert!(html.contains("<script src=\"tv-bridge.js\"></script>"));
        assert!(html.contains("background: #000"));
    }

    #[test]
    fn a_bad_descriptor_is_refused() {
        let descriptor = AppDescriptor::new("wall", "W", "1.0.0");
        assert!(bridge_js(&descriptor).is_err());
        assert!(index_html(&descriptor).is_err());
    }
}
