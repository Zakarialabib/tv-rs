//! Signage pairing and dynamic QR code session handshake ("Scan and Share" logic).
//!
//! Provides dynamic session token generation, QR code payload formatting (URI scheme and JSON),
//! expiration tracking, and peer-to-peer (P2P) handshake validation between mobile clients and
//! digital signage players.

use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use url::Url;
use uuid::Uuid;

use crate::error::{DiscoveryError, Result};

/// Default duration in seconds for dynamic QR code session token validity (5 minutes).
pub const DEFAULT_SESSION_TTL_SECS: u64 = 300;

/// URI scheme used for tv-rs digital signage pairing QR codes.
pub const SIGNAGE_PAIRING_URI_SCHEME: &str = "tvrs-signage";

/// Get current Unix timestamp in seconds.
fn current_unix_timestamp() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

/// Active pairing session generated by a digital signage player (Windows/Tauri app).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignagePairingSession {
    /// Unique player identifier.
    pub player_id: String,
    /// Human-readable player name.
    pub player_name: String,
    /// List of local IPv4 / IPv6 addresses of the player host.
    pub ip_addresses: Vec<String>,
    /// Port for incoming P2P connections.
    pub port: u16,
    /// Secure dynamic session token (UUID v4).
    pub session_token: String,
    /// Creation Unix timestamp in seconds.
    pub created_at: u64,
    /// Time-to-live in seconds.
    pub ttl_secs: u64,
}

impl SignagePairingSession {
    /// Generate a new pairing session for a signage player.
    pub fn generate(
        player_id: impl Into<String>,
        player_name: impl Into<String>,
        ip_addresses: Vec<String>,
        port: u16,
    ) -> Self {
        let created_at = current_unix_timestamp();
        let session_token = Uuid::new_v4().to_string();

        Self {
            player_id: player_id.into(),
            player_name: player_name.into(),
            ip_addresses,
            port,
            session_token,
            created_at,
            ttl_secs: DEFAULT_SESSION_TTL_SECS,
        }
    }

    /// Custom TTL constructor.
    pub fn with_ttl(mut self, ttl_secs: u64) -> Self {
        self.ttl_secs = ttl_secs;
        self
    }

    /// Expiration Unix timestamp in seconds.
    pub fn expires_at(&self) -> u64 {
        self.created_at.saturating_add(self.ttl_secs)
    }

    /// Check if the session has expired at `current_time`.
    pub fn is_expired(&self, current_time: u64) -> bool {
        current_time >= self.expires_at()
    }

    /// Create a QR code pairing payload from this session.
    pub fn to_pairing_payload(&self) -> SignagePairingPayload {
        SignagePairingPayload {
            player_id: self.player_id.clone(),
            player_name: self.player_name.clone(),
            ip_addresses: self.ip_addresses.clone(),
            port: self.port,
            session_token: self.session_token.clone(),
            expires_at: self.expires_at(),
        }
    }
}

/// Portable QR Code pairing payload scanned by mobile apps (Android/iOS).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignagePairingPayload {
    /// Player identifier.
    pub player_id: String,
    /// Player display name.
    pub player_name: String,
    /// Player IP addresses.
    pub ip_addresses: Vec<String>,
    /// P2P listening port.
    pub port: u16,
    /// Secure session token.
    pub session_token: String,
    /// Expiration timestamp (seconds since Unix epoch).
    pub expires_at: u64,
}

impl SignagePairingPayload {
    /// Serialize payload to a URI string suitable for QR code encoding
    /// (`tvrs-signage://pair?id=...&name=...&ips=192.168.1.50&port=8443&token=...&expires_at=...`).
    pub fn to_uri(&self) -> String {
        let ips = self.ip_addresses.join(",");
        format!(
            "{}://pair?id={}&name={}&ips={}&port={}&token={}&expires_at={}",
            SIGNAGE_PAIRING_URI_SCHEME,
            urlencoding::encode(&self.player_id),
            urlencoding::encode(&self.player_name),
            urlencoding::encode(&ips),
            self.port,
            urlencoding::encode(&self.session_token),
            self.expires_at
        )
    }

    /// Parse payload from a URI scheme string (`tvrs-signage://pair?...`).
    pub fn from_uri(raw_uri: &str) -> Result<Self> {
        let parsed_url =
            Url::parse(raw_uri).map_err(|e| DiscoveryError::Malformed(e.to_string()))?;

        if parsed_url.scheme() != SIGNAGE_PAIRING_URI_SCHEME {
            return Err(DiscoveryError::Malformed(format!(
                "invalid URI scheme '{}', expected '{}'",
                parsed_url.scheme(),
                SIGNAGE_PAIRING_URI_SCHEME
            )));
        }

        let mut player_id = None;
        let mut player_name = None;
        let mut ip_addresses = Vec::new();
        let mut port = None;
        let mut session_token = None;
        let mut expires_at = None;

        for (key, val) in parsed_url.query_pairs() {
            match key.as_ref() {
                "id" => player_id = Some(val.to_string()),
                "name" => player_name = Some(val.to_string()),
                "ips" => {
                    ip_addresses = val
                        .split(',')
                        .map(|s| s.trim().to_string())
                        .filter(|s| !s.is_empty())
                        .collect();
                }
                "port" => port = val.parse::<u16>().ok(),
                "token" => session_token = Some(val.to_string()),
                "expires_at" => expires_at = val.parse::<u64>().ok(),
                _ => {}
            }
        }

        let player_id =
            player_id.ok_or_else(|| DiscoveryError::Malformed("missing 'id'".to_string()))?;
        let player_name =
            player_name.ok_or_else(|| DiscoveryError::Malformed("missing 'name'".to_string()))?;
        let port = port.ok_or_else(|| DiscoveryError::Malformed("missing 'port'".to_string()))?;
        let session_token = session_token
            .ok_or_else(|| DiscoveryError::Malformed("missing 'token'".to_string()))?;
        let expires_at = expires_at
            .ok_or_else(|| DiscoveryError::Malformed("missing 'expires_at'".to_string()))?;

        Ok(Self {
            player_id,
            player_name,
            ip_addresses,
            port,
            session_token,
            expires_at,
        })
    }

    /// Serialize payload to JSON.
    pub fn to_json(&self) -> Result<String> {
        serde_json::to_string(self).map_err(|e| DiscoveryError::Malformed(e.to_string()))
    }

    /// Parse payload from JSON string.
    pub fn from_json(raw_json: &str) -> Result<Self> {
        serde_json::from_str(raw_json).map_err(|e| DiscoveryError::Malformed(e.to_string()))
    }

    /// Check if the payload token has expired.
    pub fn is_expired(&self, current_time: u64) -> bool {
        current_time >= self.expires_at
    }
}

/// P2P Handshake request sent from a mobile app after scanning the QR code.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignageHandshakeRequest {
    /// Session token obtained from scanning the QR code.
    pub session_token: String,
    /// Mobile client device ID.
    pub client_id: String,
    /// Mobile client device name (e.g. `"Pixel 8 Pro"`).
    pub client_name: String,
    /// Client timestamp (Unix epoch seconds).
    pub timestamp: u64,
}

/// P2P Handshake response returned by the signage player.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignageHandshakeResponse {
    /// Whether the P2P handshake was accepted.
    pub accepted: bool,
    /// Signage player ID.
    pub player_id: String,
    /// Granted capabilities/permissions (e.g., `"screen_share"`, `"remote_control"`).
    pub granted_permissions: Vec<String>,
    /// Error message if rejected.
    pub error: Option<String>,
}

/// Validate a P2P handshake request against an active pairing session.
pub fn validate_handshake(
    session: &SignagePairingSession,
    request: &SignageHandshakeRequest,
    current_time: u64,
) -> SignageHandshakeResponse {
    if session.is_expired(current_time) {
        return SignageHandshakeResponse {
            accepted: false,
            player_id: session.player_id.clone(),
            granted_permissions: Vec::new(),
            error: Some("Session token expired".to_string()),
        };
    }

    if session.session_token != request.session_token {
        return SignageHandshakeResponse {
            accepted: false,
            player_id: session.player_id.clone(),
            granted_permissions: Vec::new(),
            error: Some("Invalid session token".to_string()),
        };
    }

    SignageHandshakeResponse {
        accepted: true,
        player_id: session.player_id.clone(),
        granted_permissions: vec![
            "screen_share".to_string(),
            "remote_control".to_string(),
            "media_cast".to_string(),
        ],
        error: None,
    }
}

/// Module providing helper functions for urlencoding/decoding if needed internally.
mod urlencoding {
    pub fn encode(s: &str) -> String {
        url::form_urlencoded::byte_serialize(s.as_bytes()).collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_pairing_session_generation_and_expiration() {
        let session = SignagePairingSession::generate(
            "player-123",
            "Lobby Screen",
            vec!["192.168.1.50".to_string()],
            8443,
        );

        assert_eq!(session.player_id, "player-123");
        assert_eq!(session.player_name, "Lobby Screen");
        assert_eq!(session.port, 8443);
        assert!(!session.session_token.is_empty());

        let now = current_unix_timestamp();
        assert!(!session.is_expired(now));
        assert!(session.is_expired(now + session.ttl_secs + 1));
    }

    #[test]
    fn test_uri_payload_roundtrip() {
        let session = SignagePairingSession::generate(
            "player-456",
            "Boardroom Display",
            vec!["192.168.1.10".to_string(), "10.0.0.10".to_string()],
            9000,
        );

        let payload = session.to_pairing_payload();
        let uri = payload.to_uri();

        assert!(uri.starts_with("tvrs-signage://pair?"));
        assert!(uri.contains("player-456"));

        let parsed = SignagePairingPayload::from_uri(&uri).expect("Failed to parse pairing URI");
        assert_eq!(parsed.player_id, payload.player_id);
        assert_eq!(parsed.player_name, payload.player_name);
        assert_eq!(parsed.ip_addresses, payload.ip_addresses);
        assert_eq!(parsed.port, payload.port);
        assert_eq!(parsed.session_token, payload.session_token);
        assert_eq!(parsed.expires_at, payload.expires_at);
    }

    #[test]
    fn test_json_payload_roundtrip() {
        let session = SignagePairingSession::generate(
            "player-789",
            "Kiosk 1",
            vec!["192.168.1.20".to_string()],
            8080,
        );

        let payload = session.to_pairing_payload();
        let json = payload.to_json().unwrap();
        let parsed = SignagePairingPayload::from_json(&json).unwrap();

        assert_eq!(parsed, payload);
    }

    #[test]
    fn test_handshake_validation_success_and_failures() {
        let session = SignagePairingSession::generate(
            "player-1",
            "Main Screen",
            vec!["192.168.1.5".to_string()],
            8443,
        );

        let now = current_unix_timestamp();

        let req_valid = SignageHandshakeRequest {
            session_token: session.session_token.clone(),
            client_id: "phone-abc".to_string(),
            client_name: "Admin Android".to_string(),
            timestamp: now,
        };

        let res = validate_handshake(&session, &req_valid, now);
        assert!(res.accepted);
        assert!(res.error.is_none());
        assert!(res
            .granted_permissions
            .contains(&"screen_share".to_string()));

        // Invalid token
        let req_bad_token = SignageHandshakeRequest {
            session_token: "invalid-token".to_string(),
            client_id: "phone-abc".to_string(),
            client_name: "Admin Android".to_string(),
            timestamp: now,
        };
        let res_bad = validate_handshake(&session, &req_bad_token, now);
        assert!(!res_bad.accepted);
        assert_eq!(res_bad.error.as_deref(), Some("Invalid session token"));

        // Expired session
        let res_expired = validate_handshake(&session, &req_valid, now + session.ttl_secs + 10);
        assert!(!res_expired.accepted);
        assert_eq!(res_expired.error.as_deref(), Some("Session token expired"));
    }
}
